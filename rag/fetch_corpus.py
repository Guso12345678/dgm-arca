"""Download the RAG corpus listed in ``rag/sources.json`` into ``rag/corpus/``.

The documents are public legal and supervisory texts, but they are not ours to redistribute,
so the repository keeps only this script and the manifest. Run it once per machine::

    uv run python -m rag.fetch_corpus            # download what is missing
    uv run python -m rag.fetch_corpus --force    # download everything again

It also writes ``rag/corpus/README.md`` (title, URL, date, checksum and licence note of every
file), which is where the licences of the corpus are documented. Entries marked
``"manual": true`` have no stable direct link: the script tells you where to get the file.
Add your own documents by appending entries to ``rag/sources.json`` (same fields).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Callable
from datetime import UTC, datetime
from pathlib import Path

SOURCES_FILE = Path(__file__).parent / "sources.json"
CORPUS_DIR = Path(__file__).parent / "corpus"
USER_AGENT = "Mozilla/5.0 (compatible; arca-rag-corpus/1.0; academic use)"


def validate_download(content: bytes, filename: str) -> None:
    """Reject answers that are not the document (error pages, bot challenges, empty files)."""
    if len(content) < 1000:
        raise ValueError(f"only {len(content)} bytes: not a document")
    suffix = Path(filename).suffix.lower()
    if suffix == ".pdf" and not content.startswith(b"%PDF"):
        raise ValueError("the file is not a PDF (an HTML error page or a bot check?)")
    if suffix in {".html", ".htm"} and b"<" not in content[:2000]:
        raise ValueError("the file does not look like HTML")


def load_sources(path: Path = SOURCES_FILE) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))


def fetch_one(
    source: dict, corpus_dir: Path, force: bool = False, get: Callable | None = None
) -> dict:
    """Download one source, trying ``url`` and then each of ``fallback_urls`` in order.

    Returns ``{"status": ..., ...}`` and never raises on network errors. A failed attempt
    (HTTP error, bot check, an HTML page where a PDF was expected) moves on to the next URL;
    when all fail, ``error`` lists what happened with each one. ``used_url`` tells which worked.
    """
    target = corpus_dir / source["filename"]
    if target.exists() and not force:
        return {"status": "present", "path": target}
    urls = [u for u in [source.get("url"), *source.get("fallback_urls", [])] if u]
    if source.get("manual") or not urls:
        return {"status": "manual", "path": target, "note": source.get("license_note", "")}
    if get is None:
        import httpx

        get = httpx.get
    errors = []
    for url in urls:
        try:
            response = get(
                url, headers={"User-Agent": USER_AGENT}, timeout=60, follow_redirects=True
            )
            response.raise_for_status()
            validate_download(response.content, source["filename"])
        except Exception as exc:  # network, HTTP status or validation: try the next URL
            errors.append(f"{url} -> {type(exc).__name__}: {exc}")
            continue
        corpus_dir.mkdir(parents=True, exist_ok=True)
        target.write_bytes(response.content)
        return {"status": "downloaded", "path": target, "used_url": url}
    return {"status": "failed", "path": target, "error": "\n             ".join(errors)}


def write_corpus_readme(sources: list[dict], corpus_dir: Path) -> Path:
    """Document every file present in the corpus: where it comes from and under what terms."""
    lines = [
        "# Corpus (generated by `python -m rag.fetch_corpus`)",
        "",
        "Public legal and supervisory texts on consumer credit. They are not redistributed in",
        "the repository: this folder is git-ignored and rebuilt with the script.",
        "",
        "| File | Title | URL | SHA-256 | Language | Licence / reuse note |",
        "|---|---|---|---|---|---|",
    ]
    for source in sources:
        path = corpus_dir / source["filename"]
        if not path.exists():
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        origin = source.get("used_url") or source.get("url") or "manual download"
        lines.append(
            f"| `{source['filename']}` | {source['title']} | {origin} | `{digest}` | "
            f"{source.get('language', '')} | {source.get('license_note', '')} |"
        )
    lines += ["", f"Generated on {datetime.now(UTC):%Y-%m-%d} (UTC).", ""]
    readme = corpus_dir / "README.md"
    corpus_dir.mkdir(parents=True, exist_ok=True)
    readme.write_text("\n".join(lines), encoding="utf-8")
    return readme


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="download again even if present")
    parser.add_argument("--only", help="only this source id")
    args = parser.parse_args()

    sources = [s for s in load_sources() if not args.only or s["id"] == args.only]
    failures = 0
    for source in sources:
        result = fetch_one(source, CORPUS_DIR, force=args.force)
        status = result["status"]
        if "used_url" in result:
            source["used_url"] = result["used_url"]
        print(f"[{status:>10}] {source['id']:<24} {source['filename']}")
        if status == "downloaded":
            print(f"             from {result['used_url']}")
        if status == "failed":
            failures += 1
            print(f"             {result['error']}")
        elif status == "manual":
            failures += 1
            print(f"             manual step: {result['note']}")
    readme = write_corpus_readme(sources, CORPUS_DIR)
    print(f"\ncorpus README -> {readme}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
